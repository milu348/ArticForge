#!/usr/bin/env python3
"""Step 8: kinematic choreography video + interactive viewer of the adapted
asset (position actuators drive every joint to its "open" limit and back).

The scene (assets/<asset>/scene.mjcf) is generated by urdfkit from the
adapted URDF — visual meshes, position actuators, gains from config "kp".
The choreography targets are the joints' open-limit endpoints (urdfkit).
This run doubles as the joint-motion verification for the articulation
delivery (JOINT_MOTION_NOT_VERIFIED -> verified).

Modes:
  (default)  offscreen render -> assets/<asset>/<asset>_demo.mp4 + snapshots
  --view     native interactive MuJoCo viewer (real-time, orbit, sliders)

Usage:
  .venv/bin/python pipeline/8_render_video.py --asset nightstand-02 [--view]
"""
import argparse
import os
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402
import urdfkit  # noqa: E402

# choreography (s): rest -> open ramp -> hold -> close ramp -> rest
KEYS_T = [(0.0, 0.0), (0.4, 0.0), (1.2, 1.0), (2.0, 1.0), (2.9, 0.0), (3.5, 0.0)]
T_END = KEYS_T[-1][0]


def smoothstep(x):
    return x * x * (3 - 2 * x)


def targets(t, open_targets):
    """Blend rest(0) <-> open(target) along the KEYS_T piecewise-linear+ss curve."""
    out = []
    for tgt in open_targets:
        v = 0.0
        for (t0, a0), (t1, a1) in zip(KEYS_T[:-1], KEYS_T[1:]):
            if t0 <= t <= t1:
                s = smoothstep((t - t0) / (t1 - t0))
                v = a0 + s * (a1 - a0)
                break
        out.append(tgt * v)
    return out


def build(asset, model_urdf, cfg):
    import mujoco
    scene = asset / "scene.mjcf"
    scene.write_text(urdfkit.build_mjcf(asset, model_urdf, cfg, physics=False))
    model = mujoco.MjModel.from_xml_path(str(scene))
    return model, mujoco.MjData(model)


def run_view(asset, model_urdf, cfg):
    import mujoco
    import mujoco.viewer
    model, data = build(asset, model_urdf, cfg)
    joints = urdfkit.ordered_joints(model_urdf)
    open_targets = [urdfkit.open_target(j)[0] for j in joints]
    print("Interactive viewer: left-drag orbit, scroll zoom; "
          "UI -> Control panel has one slider per joint.", flush=True)
    # Double-sided rendering: LUX3D articulated meshes are single-shell
    # (open-top drawer boxes, floating handles) — backface culling makes
    # the interiors look hollow. launch_passive exposes Handle.user_scn,
    # whose mjRND flags include CULL_FACE — disable it there (the blocking
    # mujoco.viewer.launch has no flags argument in 3.17).
    with mujoco.viewer.launch_passive(model, data) as viewer:
        try:
            viewer.user_scn.flags[mujoco.mjtRndFlag.mjRND_CULL_FACE] = 0
        except AttributeError:
            pass
        # scripted demo: rest -> open -> hold -> close, then free interaction
        import time
        for phase in ("open", "hold", "close", "hold"):
            n_hold = 240 if phase.startswith("hold") else 120
            for step in range(n_hold):
                t = step / n_hold
                frac = {"open": min(t * 1.4, 1.0),
                        "hold": 1.0,
                        "close": max(1.0 - t * 1.4, 0.0),
                        "hold2": 0.0}[phase if phase != "hold" else "hold"]
                for a, v in enumerate(open_targets):
                    data.ctrl[a] = v * frac
                mujoco.mj_step(model, data)
                viewer.sync()
        # keep the window open for manual interaction (sliders + orbit)
        t_end = time.time() + 300
        while time.time() < t_end and viewer.is_running():
            mujoco.mj_step(model, data)
            viewer.sync()
            time.sleep(0.005)


def run_video(asset, model_urdf, cfg):
    import imageio
    import mujoco
    import numpy as np
    model, data = build(asset, model_urdf, cfg)
    joints = urdfkit.ordered_joints(model_urdf)
    open_targets = [urdfkit.open_target(j)[0] for j in joints]

    renderer = mujoco.Renderer(model, height=720, width=1280)
    cam_d = urdfkit.auto_camera(asset, model_urdf, cfg)
    cam = mujoco.MjvCamera()
    cam.lookat[:] = cam_d["lookat"]
    cam.distance = cam_d["distance"]
    cam.azimuth = cam_d["azimuth"]
    cam.elevation = cam_d["elevation"]

    frames = []
    steps_per_frame = 10  # 0.02 s per frame
    total_steps = int(T_END / model.opt.timestep)
    for step in range(total_steps):
        t = step * model.opt.timestep
        for a, v in enumerate(targets(t, open_targets)):
            data.ctrl[a] = v
        mujoco.mj_step(model, data)
        if step % steps_per_frame == 0:
            renderer.update_scene(data, camera=cam)
            renderer.scene.flags[mujoco.mjtRndFlag.mjRND_CULL_FACE] = 0
            frames.append(renderer.render().copy())

    video_path = asset / f"{asset.name}_demo.mp4"
    imageio.mimwrite(video_path, frames, fps=25, quality=8)
    print("video:", video_path, f"({len(frames)} frames)")

    import imageio.v3 as iio
    for frac, name in [(0.10, "closed"), (0.45, "open"), (0.95, "re-closed")]:
        idx = int(frac * (len(frames) - 1))
        iio.imwrite(asset / f"snapshot_{name}.png", frames[idx])
    for i, j in enumerate(joints):
        print(f"final {j['name']}: qpos={data.qpos[i]:+.4f} "
              f"(open target {open_targets[i]:+.4f})")
    renderer.close()


def main():
    ap = common.add_asset_arg(argparse.ArgumentParser(
        description="Step 8: kinematic video + interactive viewer"))
    ap.add_argument("--view", action="store_true", help="interactive viewer window")
    args = ap.parse_args()

    cfg = common.config(args.asset)
    asset = common.asset_dir(args.asset)
    model_urdf = urdfkit.parse_urdf(asset / f"{args.asset}.urdf")
    if args.view:
        os.environ.pop("MUJOCO_GL", None)  # native GLFW/GLX window
        run_view(asset, model_urdf, cfg)
    else:
        os.environ.setdefault("MUJOCO_GL", "egl")  # headless offscreen
        run_video(asset, model_urdf, cfg)


if __name__ == "__main__":
    main()
